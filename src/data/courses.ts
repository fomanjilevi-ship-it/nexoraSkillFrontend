function createTechnologyCourse(seed: TechnologyCourseSeed, index: number): CourseContent {
  const curriculum = seed.modules.map(([title, ...lessons], moduleIndex) => ({
    title: `${moduleIndex + 1}. ${title}`,
    lessons: lessons.map((lesson) => ({ title: lesson, duration: "20 min" })),
  }));

  return {
    id: courses.length + index + 1,
    slug: seed.slug,
    title: seed.title,
    instructor: seed.instructor,
    rating: 4.6 + (index % 4) / 10,
    reviewsCount: 34 + index * 7,
    studentsCount: 280 + index * 115,
    price: index % 5 === 0 ? 0 : 19.99 + (index % 4) * 5,
    level: seed.level,
    category: seed.category,
    technology: seed.technology,
    technologyLogos: seed.logos,
    technologyLogoColors: seed.logoColors,
    technologyColor: seed.color,
    description: seed.description,
    duration: "4 h 00",
    language: "Français",
    updatedAt: "Octobre 2026",
    instructorBio: `Formateur spécialisé en ${seed.technology}, ${seed.instructor} accompagne les apprenants dans la réalisation de projets web et mobiles concrets.`,
    outcomes: seed.outcomes,
    requirements: seed.requirements,
    curriculum,
  };
}

courses.push(...technologyCourseSeeds.map(createTechnologyCourse));
